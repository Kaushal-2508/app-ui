-- =============================================================
-- Notice Board: publishing a notice notifies every recipient in-app
-- -------------------------------------------------------------
-- Spec: docs/superpowers/specs/2026-09-07-notice-in-app-notifications.md
-- (frontend half shipped on naman-erp 2026-09-08: bell icons for
-- notice_published / notice_urgent, urgent alert sound, ?notice=<id> deep link
-- into /school/notices).
--
-- 1. publish_notice(): full re-emit of the LIVE body (taken from pg_proc on
--    2026-09-08, not from an older migration file) plus one INSERT ... SELECT
--    that writes a notifications row per notice_recipients row in the same
--    transaction. Deviation from the spec, on purpose: the block sits AFTER
--    "GET DIAGNOSTICS _n = ROW_COUNT" so notices.recipient_count keeps counting
--    recipients; between the recipients INSERT and that line it would have
--    counted notifications instead.
--    Verified before writing: notifications.type has no CHECK; notifications
--    .user_id is ON DELETE CASCADE; idx_notifications_unread (user_id, is_read)
--    WHERE is_read = false exists; notifications is in supabase_realtime.
--
-- 2. mark_notice_read(): also marks the reader's bell rows for that notice as
--    read, so the bell stops nagging about a notice already opened on the
--    board. Bounded by the partial unread index on (user_id, is_read); no
--    expression index needed because a user's unread set is small.
--
-- 3. Grants: publish_notice, mark_notice_read and communication_overview all
--    carried PUBLIC EXECUTE ({=X/postgres,...}), i.e. anon could call them.
--    REVOKE FROM PUBLIC and FROM anon by name (CLAUDE.md 26), GRANT to
--    authenticated.
--
-- APPLIED TO PROD 2026-09-08 via scripts/run-sql.ps1. Verified: no PUBLIC/anon EXECUTE
-- on the three functions; functional probe (rolled back): a teacher's urgent class
-- notice to 10 recipients wrote exactly 10 notice_urgent rows, none for the author,
-- link /school/notices?notice=<id>; mark_notice_read set read_at and flipped the
-- reader's bell row to is_read. Do not edit this file again; write a new one.
-- =============================================================

CREATE OR REPLACE FUNCTION public.publish_notice(_notice_id uuid, _title text, _content text, _type text, _priority text, _scope text, _class_ids uuid[] DEFAULT NULL::uuid[], _wing_ids uuid[] DEFAULT NULL::uuid[], _audience_roles text[] DEFAULT NULL::text[], _teacher_ids uuid[] DEFAULT NULL::uuid[], _requires_acknowledgement boolean DEFAULT false, _expires_at timestamp with time zone DEFAULT NULL::timestamp with time zone, _attachments jsonb DEFAULT '[]'::jsonb)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  _author    uuid := (SELECT auth.uid());
  _inst      uuid;
  _is_admin  boolean;
  _is_coord  boolean;
  _is_teach  boolean;
  _teacher_only boolean;
  _roles     text[];
  _n         integer;
BEGIN
  IF _author IS NULL THEN
    RAISE EXCEPTION 'You must be signed in to publish a notice.';
  END IF;

  IF EXISTS (SELECT 1 FROM public.notices WHERE id = _notice_id) THEN
    RETURN _notice_id;
  END IF;

  _inst := public.get_user_institution(_author);
  IF _inst IS NULL THEN
    RAISE EXCEPTION 'Your account is not linked to a school yet.';
  END IF;

  IF coalesce(btrim(_title), '') = '' THEN
    RAISE EXCEPTION 'A notice needs a title.';
  END IF;
  IF coalesce(btrim(_content), '') = '' THEN
    RAISE EXCEPTION 'A notice needs some content.';
  END IF;
  IF _scope NOT IN ('institution','wing','class') THEN
    RAISE EXCEPTION 'Choose who this notice is for.';
  END IF;

  _is_admin := public.is_institution_admin(_author, _inst);
  _is_coord := public.has_role(_author, 'coordinator');
  _is_teach := public.has_role(_author, 'teacher');
  _teacher_only := _is_teach AND NOT _is_admin AND NOT _is_coord;

  IF NOT (_is_admin OR _is_coord OR _is_teach) THEN
    RAISE EXCEPTION 'You do not have permission to publish notices.';
  END IF;

  IF _scope = 'class' THEN
    IF _class_ids IS NULL OR cardinality(_class_ids) = 0 THEN
      RAISE EXCEPTION 'Pick at least one class.';
    END IF;
    IF EXISTS (SELECT 1 FROM public.classes c
                WHERE c.id = ANY(_class_ids) AND c.institution_id <> _inst) THEN
      RAISE EXCEPTION 'That class belongs to another school.';
    END IF;
    IF NOT _is_admin THEN
      IF EXISTS (
        SELECT 1 FROM unnest(_class_ids) cid
         WHERE NOT (
           (_is_coord AND public.is_coordinator_for_class(_author, cid))
           OR (_is_teach AND public.is_teacher_for_class(_author, cid))
         )
      ) THEN
        RAISE EXCEPTION 'You can only send notices to your own classes.';
      END IF;
    END IF;

    -- A teacher reaches the students of their class and nobody else on staff.
    -- The wing coordinator is still added -- that branch ignores this list.
    IF _teacher_only THEN
      _roles := ARRAY['student'];
    ELSE
      _roles := coalesce(_audience_roles, ARRAY['student','teacher']);
      IF NOT (_roles <@ ARRAY['student','teacher']) THEN
        RAISE EXCEPTION 'A class notice can only address students and teachers.';
      END IF;
    END IF;

  ELSIF _scope = 'wing' THEN
    IF _wing_ids IS NULL OR cardinality(_wing_ids) = 0 THEN
      RAISE EXCEPTION 'Pick at least one wing.';
    END IF;
    IF EXISTS (SELECT 1 FROM public.wings w
                WHERE w.id = ANY(_wing_ids) AND w.institution_id <> _inst) THEN
      RAISE EXCEPTION 'That wing belongs to another school.';
    END IF;
    IF NOT _is_admin THEN
      IF NOT _is_coord THEN
        RAISE EXCEPTION 'Only coordinators and admins can send a wing notice.';
      END IF;
      IF EXISTS (
        SELECT 1 FROM unnest(_wing_ids) wid
         WHERE NOT EXISTS (SELECT 1 FROM public.wing_assignments wa
                            WHERE wa.user_id = _author AND wa.wing_id = wid)
      ) THEN
        RAISE EXCEPTION 'You can only send notices to your own wings.';
      END IF;
    END IF;
    _roles := coalesce(_audience_roles, ARRAY['teacher','student']);

  ELSE
    IF NOT _is_admin THEN
      RAISE EXCEPTION 'Only school admins can send a whole-school notice.';
    END IF;
    _roles := coalesce(_audience_roles, ARRAY['coordinator','teacher','student']);
  END IF;

  IF _teacher_only THEN
    IF EXISTS (SELECT 1 FROM unnest(_roles) r WHERE r <> 'student') THEN
      RAISE EXCEPTION 'Teachers can only send notices to students.';
    END IF;
    IF _teacher_ids IS NOT NULL AND cardinality(_teacher_ids) > 0 THEN
      RAISE EXCEPTION 'Teachers can only send notices to students.';
    END IF;
  END IF;

  IF NOT (_roles <@ ARRAY['coordinator','teacher','student']) THEN
    RAISE EXCEPTION 'Unknown audience.';
  END IF;

  INSERT INTO public.notices (
    id, institution_id, title, content, type, scope, priority,
    audience_roles, requires_acknowledgement, expires_at, attachments,
    published_by, published_at
  ) VALUES (
    -- order must track the column list above: type, scope, priority
    _notice_id, _inst, btrim(_title), _content, _type, _scope, _priority,
    coalesce(_roles, ARRAY['student']), _requires_acknowledgement, _expires_at,
    coalesce(_attachments, '[]'::jsonb),
    _author, now()
  );

  IF _scope = 'class' THEN
    INSERT INTO public.notice_target_classes (notice_id, class_id)
    SELECT _notice_id, cid FROM unnest(_class_ids) cid
    ON CONFLICT DO NOTHING;
  ELSIF _scope = 'wing' THEN
    INSERT INTO public.notice_target_wings (notice_id, wing_id)
    SELECT _notice_id, wid FROM unnest(_wing_ids) wid
    ON CONFLICT DO NOTHING;
  END IF;

  INSERT INTO public.notice_recipients (notice_id, user_id, recipient_role, added_reason)
  SELECT _notice_id, e.user_id, e.recipient_role, e.added_reason
    FROM public.notice_expand_audience(
           _inst, _author, _scope, _class_ids, _wing_ids, _roles, _teacher_ids) e
  ON CONFLICT (notice_id, user_id) DO NOTHING;

  GET DIAGNOSTICS _n = ROW_COUNT;

  -- One in-app notification per recipient, in the SAME transaction as the
  -- recipient rows (CLAUDE.md 9a: two dependent writes are one RPC; 23: one
  -- INSERT ... SELECT, never a client loop). Placed AFTER GET DIAGNOSTICS so
  -- recipient_count still counts recipients, not notifications. The audience
  -- already excludes the author (notice_expand_audience), and the early return
  -- above keeps a retried publish from notifying twice. The type encodes
  -- urgency so the bell picks the alert sound without reading metadata.
  INSERT INTO public.notifications (user_id, type, title, message, link, metadata)
  SELECT r.user_id,
         CASE WHEN _priority = 'urgent' THEN 'notice_urgent' ELSE 'notice_published' END,
         CASE WHEN _priority = 'urgent'    THEN 'Urgent notice: '    || btrim(_title)
              WHEN _priority = 'important' THEN 'Important notice: ' || btrim(_title)
              ELSE 'New notice: ' || btrim(_title) END,
         left(regexp_replace(_content, '\s+', ' ', 'g'), 140)
           || CASE WHEN length(_content) > 140 THEN '...' ELSE '' END,
         '/school/notices?notice=' || _notice_id::text,
         jsonb_build_object(
           'notice_id', _notice_id,
           'priority',  _priority,
           'type',      _type,
           'scope',     _scope,
           'requires_acknowledgement', _requires_acknowledgement
         )
    FROM public.notice_recipients r
   WHERE r.notice_id = _notice_id;

  UPDATE public.notices
     SET recipient_count = _n,
         audience_roles  = (SELECT coalesce(array_agg(DISTINCT r.recipient_role),
                                            ARRAY['student'])
                              FROM public.notice_recipients r
                             WHERE r.notice_id = _notice_id)
   WHERE id = _notice_id;

  RETURN _notice_id;
END $function$;

-- 2. mark_notice_read: close the loop on the bell ------------------------------
CREATE OR REPLACE FUNCTION public.mark_notice_read(_notice_id uuid, _acknowledge boolean DEFAULT false)
 RETURNS void
 LANGUAGE sql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  UPDATE public.notice_recipients
     SET read_at         = COALESCE(read_at, now()),
         acknowledged_at = CASE WHEN _acknowledge
                                THEN COALESCE(acknowledged_at, now())
                                ELSE acknowledged_at END
   WHERE notice_id = _notice_id
     AND user_id   = (SELECT auth.uid());

  -- Same gesture, same meaning for the bell. Filtered first by the partial
  -- unread index (user_id, is_read) so the jsonb test runs on a handful of rows.
  UPDATE public.notifications
     SET is_read = true
   WHERE user_id = (SELECT auth.uid())
     AND is_read = false
     AND type IN ('notice_published', 'notice_urgent')
     AND (metadata->>'notice_id') = _notice_id::text;
$function$;

-- 3. Grants (26: REVOKE FROM anon BY NAME; FROM PUBLIC alone does not strip it)
REVOKE ALL ON FUNCTION public.publish_notice(uuid, text, text, text, text, text, uuid[], uuid[], text[], uuid[], boolean, timestamp with time zone, jsonb) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.mark_notice_read(uuid, boolean) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.communication_overview(uuid)   FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.publish_notice(uuid, text, text, text, text, text, uuid[], uuid[], text[], uuid[], boolean, timestamp with time zone, jsonb) TO authenticated;
GRANT EXECUTE ON FUNCTION public.mark_notice_read(uuid, boolean) TO authenticated;
GRANT EXECUTE ON FUNCTION public.communication_overview(uuid)   TO authenticated;

