-- =============================================================
-- School Diary: table, authority helpers, RLS, RPCs, notification fan-out
-- -------------------------------------------------------------
-- Spec: docs/superpowers/specs/2026-09-07-school-diary-design.md. The frontend
-- (naman-erp, merged 2026-09-08) is gated on the `school_diary` institution
-- feature and calls diary_feed / diary_write_entry / diary_delete_entry with
-- exactly the argument names and result columns below; until this is applied
-- it detects PGRST202 and shows "not switched on yet".
--
-- Deviations from the spec, on purpose:
-- * diary_feed computes the caller's visible class ids ONCE per call (arrays)
--   instead of evaluating is_teacher_for_class / is_coordinator_for_class per
--   row; teacher_controls_student is still evaluated per single-student row
--   (§25: sharing a class is not authority over a student).
-- * The student roster is class_assignments WHERE role = 'student', the same
--   source notice_expand_audience uses; the spec's "student_class_assignments"
--   does not exist.
-- * Class labels use the notice_target_options convention (name-section) so
--   the picker and the card agree.
--
-- Contracts honoured: §21 (student_id CASCADE, created_by SET NULL, every FK
-- indexed), §23 (keyset pagination, LIMIT capped at 50, bounded fan-out in one
-- statement), §24 (entry_date from institutions.timezone), §25
-- (teacher_controls_student for single-student writes and reads), §26
-- (SECURITY DEFINER helpers in policies, (SELECT auth.uid()), REVOKE FROM anon
-- BY NAME), §9a (no INSERT/UPDATE policy: writes only through the RPCs).
--
-- APPLIED TO PROD 2026-09-08 via scripts/run-sql.ps1. Verified: table, RLS (select +
-- delete only), 5 indexes, 4 FKs with the §21 ON DELETE rules, no PUBLIC/anon
-- EXECUTE on the six functions. Functional probe in the pilot school (rolled back):
-- class homework entry -> 8 of 8 students notified, author not; feed row carries
-- class_label/author_name/can_manage; single-student remark -> exactly 1 bell row;
-- due_date on a note refused; addressed student sees both, a student from another
-- class sees neither; student delete refused; author delete removes the row. The
-- `school_diary` flag is ON for Salci National School, so the tab is live there.
-- Do not edit this file again; write a new one.
-- =============================================================

-- ── 1. Table ────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.diary_entries (
  id             uuid PRIMARY KEY,                                   -- client-generated (idempotent write)
  institution_id uuid NOT NULL REFERENCES public.institutions(id) ON DELETE CASCADE,
  class_id       uuid NOT NULL REFERENCES public.classes(id)      ON DELETE CASCADE,
  student_id     uuid          REFERENCES public.profiles(id)     ON DELETE CASCADE,  -- NULL = whole class
  kind           text NOT NULL CHECK (kind IN ('homework','remark','reminder','appreciation','note')),
  title          text NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 120),
  body           text NOT NULL CHECK (length(btrim(body)) > 0),
  due_date       date,                                              -- homework only (enforced in the RPC)
  entry_date     date NOT NULL,                                     -- institution-local day (§24)
  created_by     uuid          REFERENCES public.profiles(id)     ON DELETE SET NULL,
  created_at     timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.diary_entries IS
  'School Diary: one short entry from a teacher to a class (student_id NULL) or to one student. No UPDATE in v1; delete and rewrite. Writes only via diary_write_entry.';

CREATE INDEX IF NOT EXISTS diary_entries_class_created_idx
  ON public.diary_entries (class_id, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS diary_entries_student_created_idx
  ON public.diary_entries (student_id, created_at DESC) WHERE student_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS diary_entries_institution_idx
  ON public.diary_entries (institution_id, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS diary_entries_created_by_idx
  ON public.diary_entries (created_by);

ALTER TABLE public.diary_entries ENABLE ROW LEVEL SECURITY;

-- ── 2. Authority helpers (SECURITY DEFINER, so policies never inline EXISTS) ─

-- May _user_id write an entry for _class_id (and, if given, for _student_id)?
CREATE OR REPLACE FUNCTION public.diary_can_write_for(_class_id uuid, _student_id uuid, _user_id uuid)
RETURNS boolean
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_class_inst uuid;
  v_inst       uuid;
BEGIN
  IF _user_id IS NULL OR _class_id IS NULL THEN RETURN false; END IF;

  SELECT c.institution_id INTO v_class_inst FROM public.classes c WHERE c.id = _class_id;
  IF v_class_inst IS NULL THEN RETURN false; END IF;

  v_inst := public.get_user_institution(_user_id);
  IF v_inst IS DISTINCT FROM v_class_inst THEN RETURN false; END IF;

  -- A single-student entry must name a student who is actually on that roster.
  IF _student_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.class_assignments ca
    WHERE ca.class_id = _class_id AND ca.user_id = _student_id AND ca.role::text = 'student'
  ) THEN
    RETURN false;
  END IF;

  IF public.is_institution_admin(_user_id, v_inst) THEN RETURN true; END IF;

  IF public.has_role(_user_id, 'coordinator') AND public.is_coordinator_for_class(_user_id, _class_id) THEN
    RETURN true;
  END IF;

  IF public.has_role(_user_id, 'teacher') AND public.is_teacher_for_class(_user_id, _class_id) THEN
    -- §25: a whole-class entry needs the class; a single student needs subject
    -- authority over that student, not merely a shared class.
    RETURN _student_id IS NULL OR public.teacher_controls_student(_user_id, _student_id);
  END IF;

  RETURN false;
END $$;

-- May _user_id read entry _entry_id?
CREATE OR REPLACE FUNCTION public.diary_can_read(_entry_id uuid, _user_id uuid)
RETURNS boolean
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE
  r      record;
  v_inst uuid;
BEGIN
  IF _user_id IS NULL THEN RETURN false; END IF;
  SELECT e.institution_id, e.class_id, e.student_id, e.created_by
    INTO r FROM public.diary_entries e WHERE e.id = _entry_id;
  IF NOT FOUND THEN RETURN false; END IF;

  IF r.created_by = _user_id THEN RETURN true; END IF;

  v_inst := public.get_user_institution(_user_id);
  IF v_inst IS DISTINCT FROM r.institution_id THEN RETURN false; END IF;

  -- The student it is for, or any student of the class for a whole-class entry.
  IF r.student_id = _user_id THEN RETURN true; END IF;
  IF r.student_id IS NULL AND EXISTS (
    SELECT 1 FROM public.class_assignments ca
    WHERE ca.class_id = r.class_id AND ca.user_id = _user_id AND ca.role::text = 'student'
  ) THEN
    RETURN true;
  END IF;

  IF public.is_institution_admin(_user_id, v_inst) THEN RETURN true; END IF;
  IF public.has_role(_user_id, 'coordinator') AND public.is_coordinator_for_class(_user_id, r.class_id) THEN
    RETURN true;
  END IF;
  IF public.has_role(_user_id, 'teacher') AND public.is_teacher_for_class(_user_id, r.class_id) THEN
    RETURN r.student_id IS NULL OR public.teacher_controls_student(_user_id, r.student_id);
  END IF;
  RETURN false;
END $$;

-- May _user_id remove entry _entry_id? The author, or an admin of that school.
CREATE OR REPLACE FUNCTION public.diary_can_manage(_entry_id uuid, _user_id uuid)
RETURNS boolean
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE r record;
BEGIN
  IF _user_id IS NULL THEN RETURN false; END IF;
  SELECT e.institution_id, e.created_by INTO r FROM public.diary_entries e WHERE e.id = _entry_id;
  IF NOT FOUND THEN RETURN false; END IF;
  RETURN r.created_by = _user_id OR public.is_institution_admin(_user_id, r.institution_id);
END $$;

-- ── 3. RLS: read and delete through the helpers; NO insert/update policy ────
DROP POLICY IF EXISTS diary_entries_select ON public.diary_entries;
CREATE POLICY diary_entries_select ON public.diary_entries
  FOR SELECT TO authenticated
  USING (public.diary_can_read(id, (SELECT auth.uid())));

DROP POLICY IF EXISTS diary_entries_delete ON public.diary_entries;
CREATE POLICY diary_entries_delete ON public.diary_entries
  FOR DELETE TO authenticated
  USING (public.diary_can_manage(id, (SELECT auth.uid())));

-- ── 4. diary_feed: newest first, keyset paged, scoped to the caller ─────────
CREATE OR REPLACE FUNCTION public.diary_feed(
  _class_id          uuid        DEFAULT NULL,
  _student_id        uuid        DEFAULT NULL,
  _kind              text        DEFAULT NULL,
  _before_created_at timestamptz DEFAULT NULL,
  _before_id         uuid        DEFAULT NULL,
  _limit             integer     DEFAULT 20
)
RETURNS TABLE (
  id           uuid,
  class_id     uuid,
  class_label  text,
  student_id   uuid,
  student_name text,
  kind         text,
  title        text,
  body         text,
  due_date     date,
  entry_date   date,
  created_at   timestamptz,
  author_id    uuid,
  author_name  text,
  can_manage   boolean
)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_uid             uuid := (SELECT auth.uid());
  v_inst            uuid;
  v_admin           boolean := false;
  v_student_classes uuid[] := '{}';
  v_coord_classes   uuid[] := '{}';
  v_teach_classes   uuid[] := '{}';
  v_lim             integer := LEAST(GREATEST(COALESCE(_limit, 20), 1), 50);
BEGIN
  IF v_uid IS NULL THEN RAISE EXCEPTION 'You must be signed in.'; END IF;
  v_inst := public.get_user_institution(v_uid);
  IF v_inst IS NULL THEN RETURN; END IF;

  v_admin := public.is_institution_admin(v_uid, v_inst);

  -- Scope computed ONCE per call, not per row (§23).
  IF NOT v_admin THEN
    SELECT COALESCE(array_agg(ca.class_id), '{}') INTO v_student_classes
      FROM public.class_assignments ca
     WHERE ca.user_id = v_uid AND ca.role::text = 'student';

    IF public.has_role(v_uid, 'coordinator') THEN
      SELECT COALESCE(array_agg(c.id), '{}') INTO v_coord_classes
        FROM public.classes c
       WHERE c.institution_id = v_inst AND public.is_coordinator_for_class(v_uid, c.id);
    END IF;

    IF public.has_role(v_uid, 'teacher') THEN
      SELECT COALESCE(array_agg(c.id), '{}') INTO v_teach_classes
        FROM public.classes c
       WHERE c.institution_id = v_inst AND public.is_teacher_for_class(v_uid, c.id);
    END IF;
  END IF;

  RETURN QUERY
  SELECT e.id,
         e.class_id,
         (c.name || CASE WHEN COALESCE(c.section, '') <> '' THEN '-' || c.section ELSE '' END)::text AS class_label,
         e.student_id,
         sp.full_name AS student_name,
         e.kind, e.title, e.body, e.due_date, e.entry_date, e.created_at,
         e.created_by AS author_id,
         ap.full_name AS author_name,
         (v_admin OR e.created_by = v_uid) AS can_manage
    FROM public.diary_entries e
    JOIN public.classes c        ON c.id = e.class_id
    LEFT JOIN public.profiles sp ON sp.id = e.student_id
    LEFT JOIN public.profiles ap ON ap.id = e.created_by
   WHERE e.institution_id = v_inst
     AND (_class_id   IS NULL OR e.class_id   = _class_id)
     AND (_student_id IS NULL OR e.student_id = _student_id)
     AND (_kind       IS NULL OR e.kind       = _kind)
     AND (_before_created_at IS NULL OR _before_id IS NULL
          OR (e.created_at, e.id) < (_before_created_at, _before_id))
     AND (
           v_admin
        OR e.created_by = v_uid
        OR e.student_id = v_uid
        OR (e.student_id IS NULL AND e.class_id = ANY (v_student_classes))
        OR e.class_id = ANY (v_coord_classes)
        OR (e.class_id = ANY (v_teach_classes)
            AND (e.student_id IS NULL OR public.teacher_controls_student(v_uid, e.student_id)))
     )
   ORDER BY e.created_at DESC, e.id DESC
   LIMIT v_lim;
END $$;

-- ── 5. diary_write_entry: validate, write, notify, in one transaction ───────
CREATE OR REPLACE FUNCTION public.diary_write_entry(
  _entry_id   uuid,
  _class_id   uuid,
  _student_id uuid DEFAULT NULL,
  _kind       text DEFAULT NULL,
  _title      text DEFAULT NULL,
  _body       text DEFAULT NULL,
  _due_date   date DEFAULT NULL
)
RETURNS uuid
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_uid        uuid := (SELECT auth.uid());
  v_inst       uuid;
  v_tz         text;
  v_entry_date date;
BEGIN
  IF v_uid IS NULL THEN RAISE EXCEPTION 'You must be signed in.'; END IF;
  IF _entry_id IS NULL OR _class_id IS NULL THEN RAISE EXCEPTION 'This entry is missing its class.'; END IF;

  -- Idempotent: a double-tap or a retry with the same id writes nothing new.
  IF EXISTS (SELECT 1 FROM public.diary_entries WHERE id = _entry_id) THEN
    RETURN _entry_id;
  END IF;

  IF _kind IS NULL OR _kind NOT IN ('homework','remark','reminder','appreciation','note') THEN
    RAISE EXCEPTION 'Pick what kind of entry this is.';
  END IF;
  IF COALESCE(btrim(_title), '') = '' THEN RAISE EXCEPTION 'The entry needs a title.'; END IF;
  IF length(btrim(_title)) > 120 THEN RAISE EXCEPTION 'Keep the title under 120 characters.'; END IF;
  IF COALESCE(btrim(_body), '') = '' THEN RAISE EXCEPTION 'The entry needs some details.'; END IF;
  IF _due_date IS NOT NULL AND _kind <> 'homework' THEN
    RAISE EXCEPTION 'Only homework entries take a due date.';
  END IF;

  SELECT c.institution_id INTO v_inst FROM public.classes c WHERE c.id = _class_id;
  IF v_inst IS NULL THEN RAISE EXCEPTION 'That class no longer exists.'; END IF;

  IF NOT public.diary_can_write_for(_class_id, _student_id, v_uid) THEN
    RAISE EXCEPTION 'You can only write diary entries for your own classes and students.';
  END IF;

  -- §24: the diary day is the school's local day, never the server's.
  SELECT i.timezone INTO v_tz FROM public.institutions i WHERE i.id = v_inst;
  v_entry_date := (now() AT TIME ZONE COALESCE(v_tz, 'Asia/Kolkata'))::date;

  INSERT INTO public.diary_entries
    (id, institution_id, class_id, student_id, kind, title, body, due_date, entry_date, created_by)
  VALUES
    (_entry_id, v_inst, _class_id, _student_id, _kind, btrim(_title), _body, _due_date, v_entry_date, v_uid)
  ON CONFLICT (id) DO NOTHING;

  -- One bell row per addressed student, same transaction, one statement. The
  -- roster is class_assignments role='student' (what notice_expand_audience
  -- uses). The author is never notified.
  INSERT INTO public.notifications (user_id, type, title, message, link, metadata)
  SELECT s.uid,
         'diary_' || _kind,
         CASE _kind
           WHEN 'homework'     THEN 'Homework: '     || btrim(_title)
           WHEN 'remark'       THEN 'Remark: '       || btrim(_title)
           WHEN 'reminder'     THEN 'Reminder: '     || btrim(_title)
           WHEN 'appreciation' THEN 'Appreciation: ' || btrim(_title)
           ELSE                     'Diary: '        || btrim(_title)
         END,
         left(regexp_replace(_body, '\s+', ' ', 'g'), 140),
         '/school/communication?tab=diary',
         jsonb_build_object('entry_id', _entry_id, 'kind', _kind, 'class_id', _class_id)
    FROM (
      SELECT _student_id AS uid WHERE _student_id IS NOT NULL
      UNION
      SELECT ca.user_id
        FROM public.class_assignments ca
        JOIN public.profiles p ON p.id = ca.user_id
       WHERE _student_id IS NULL
         AND ca.class_id = _class_id
         AND ca.role::text = 'student'
         AND p.is_active IS NOT FALSE
    ) s
   WHERE s.uid IS NOT NULL AND s.uid <> v_uid;

  RETURN _entry_id;
END $$;

-- ── 6. diary_delete_entry ───────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.diary_delete_entry(_entry_id uuid)
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_uid uuid := (SELECT auth.uid());
BEGIN
  IF v_uid IS NULL THEN RAISE EXCEPTION 'You must be signed in.'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.diary_entries WHERE id = _entry_id) THEN
    RETURN;  -- already gone: a retried delete is not an error
  END IF;
  IF NOT public.diary_can_manage(_entry_id, v_uid) THEN
    RAISE EXCEPTION 'Only the author or a school admin can remove this entry.';
  END IF;
  DELETE FROM public.diary_entries WHERE id = _entry_id;
END $$;

-- ── 7. Grants (§26) ─────────────────────────────────────────────────────────
-- The helpers run inside RLS policies evaluated as the caller, so authenticated
-- needs EXECUTE on them too; anon and PUBLIC get nothing, by name.
REVOKE ALL ON FUNCTION public.diary_can_write_for(uuid, uuid, uuid) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.diary_can_read(uuid, uuid)            FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.diary_can_manage(uuid, uuid)          FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.diary_feed(uuid, uuid, text, timestamptz, uuid, integer) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.diary_write_entry(uuid, uuid, uuid, text, text, text, date) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.diary_delete_entry(uuid)              FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.diary_can_write_for(uuid, uuid, uuid) TO authenticated;
GRANT EXECUTE ON FUNCTION public.diary_can_read(uuid, uuid)            TO authenticated;
GRANT EXECUTE ON FUNCTION public.diary_can_manage(uuid, uuid)          TO authenticated;
GRANT EXECUTE ON FUNCTION public.diary_feed(uuid, uuid, text, timestamptz, uuid, integer) TO authenticated;
GRANT EXECUTE ON FUNCTION public.diary_write_entry(uuid, uuid, uuid, text, text, text, date) TO authenticated;
GRANT EXECUTE ON FUNCTION public.diary_delete_entry(uuid)              TO authenticated;

