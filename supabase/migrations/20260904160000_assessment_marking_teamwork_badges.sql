EXECUTE FUNCTION public.tg_zz_teacher_badges_creator();

-- 4d. final_results. HOT: validating one exam writes one row per attempt in a
--     single statement, and publishing flips is_published on all of them at
--     once. Statement-level, both actor columns unioned, one evaluator run per
--     distinct person. INSERT covers validation (finalized_by is NOT NULL at
--     insert); the UPDATE half covers publish and any re-validation.
CREATE OR REPLACE FUNCTION public.tg_zz_teacher_badges_results()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE r record;
BEGIN
  BEGIN
    FOR r IN
      SELECT DISTINCT u.teacher_id
      FROM (
        SELECT n.finalized_by AS teacher_id FROM newrows n
        UNION
        SELECT n.published_by FROM newrows n
      ) u
      WHERE u.teacher_id IS NOT NULL
    LOOP
      PERFORM public.evaluate_teacher_badges(r.teacher_id);
    END LOOP;
  EXCEPTION WHEN OTHERS THEN
    RAISE WARNING 'tg_zz_teacher_badges_results failed: %', SQLERRM;
  END;
  RETURN NULL;
END $$;

DROP TRIGGER IF EXISTS trg_zz_teacher_badges_results ON public.final_results;
CREATE TRIGGER trg_zz_teacher_badges_results
AFTER INSERT ON public.final_results
REFERENCING NEW TABLE AS newrows
FOR EACH STATEMENT
EXECUTE FUNCTION public.tg_zz_teacher_badges_results();

-- No column list here on purpose: Postgres refuses "UPDATE OF col ...
-- REFERENCING NEW TABLE" (SQLSTATE 0A000, "transition tables cannot be
-- specified for triggers with column lists"), which is how the first apply of
-- 20260904150000 failed on 2026-09-07. Any UPDATE of final_results therefore
-- runs this function once per statement; it costs one DISTINCT over the
-- transition table plus one evaluator run per actor named in it, and a
