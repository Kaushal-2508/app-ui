DROP TRIGGER IF EXISTS trg_zz_teacher_badges_results_upd ON public.final_results;
CREATE TRIGGER trg_zz_teacher_badges_results_upd
AFTER UPDATE ON public.final_results
REFERENCING NEW TABLE AS newrows
FOR EACH STATEMENT
EXECUTE FUNCTION public.tg_zz_teacher_badges_results();

