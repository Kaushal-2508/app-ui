-- ── 5. Backfill ─────────────────────────────────────────────────────────────
-- Retroactive award for the nine new metrics. The pre-filter is on the NEW
-- predicates only: everyone with activity on the first nine was evaluated by
-- the two previous backfills, and re-running the evaluator is idempotent
-- anyway. _notify = false, one summary notification per user.
DO $$
DECLARE r record; v_total int := 0; v_seen int := 0; v_n int := 0;
BEGIN
  FOR r IN
    SELECT DISTINCT ur.user_id AS id
    FROM user_roles ur
    WHERE ur.role IN ('teacher', 'coordinator')
      AND (
           EXISTS (SELECT 1 FROM exams e            WHERE e.created_by = ur.user_id
                                                      AND e.status IN ('published','active','completed'))
        OR EXISTS (SELECT 1 FROM question_bank q    WHERE q.created_by = ur.user_id
                                                      AND q.source IN ('manual','ai_generated'))
        OR EXISTS (SELECT 1 FROM exam_templates t   WHERE t.created_by = ur.user_id)
        OR EXISTS (SELECT 1 FROM final_results fr   WHERE fr.finalized_by = ur.user_id
                                                       OR fr.published_by = ur.user_id)
        OR EXISTS (SELECT 1 FROM student_remarks sr WHERE sr.teacher_id = ur.user_id)
        OR EXISTS (SELECT 1 FROM tt_substitutions s WHERE s.substitute_teacher_id = ur.user_id
                                                      AND s.status IN ('assigned','completed'))
        OR EXISTS (SELECT 1 FROM leave_requests lr  WHERE lr.reviewed_by = ur.user_id
                                                      AND lr.status IN ('approved','rejected')
                                                      AND lr.source = 'student')
      )
  LOOP
    v_seen  := v_seen + 1;
    v_n     := public.evaluate_teacher_badges(r.id, false);
    v_total := v_total + v_n;

    IF v_n > 0 THEN
      BEGIN
        INSERT INTO notifications (user_id, type, title, message, link, metadata)
        VALUES (
          r.id, 'badge_earned',
          'You have ' || v_n || CASE WHEN v_n = 1 THEN ' new teaching badge'
                                     ELSE ' new teaching badges' END,
          'Your teaching work so far has been recognised. Open Achievements to see '
            || CASE WHEN v_n = 1 THEN 'it.' ELSE 'them.' END,
          '/achievements',
          jsonb_build_object('backfill', true, 'awarded', v_n)
        );
      EXCEPTION WHEN OTHERS THEN
        RAISE WARNING 'round-3 badge backfill: awards committed, summary notification failed for %: %', r.id, SQLERRM;
      END;
    END IF;
  END LOOP;
  RAISE NOTICE 'round-3 badge backfill: % users evaluated, % badges awarded', v_seen, v_total;
END $$;

