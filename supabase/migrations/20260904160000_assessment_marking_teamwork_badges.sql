-- ── 3. The evaluator ────────────────────────────────────────────────────────
-- Full re-emit: the 20260904150000 body plus nine counters. Diff against the
-- live pg_get_functiondef before applying; the ONLY expected differences are
-- the nine v_* declarations, their SELECTs, the nine VALUES rows and the
-- GREATEST(...) arguments.
CREATE OR REPLACE FUNCTION public.evaluate_teacher_badges(
  _user_id uuid,
  _notify  boolean DEFAULT true
)
RETURNS int
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_inst          uuid;
  v_attendance    int := 0;
  v_lessons       int := 0;
  v_exams         int := 0;
  v_answers       int := 0;
  v_hw_created    int := 0;
  v_hw_marked     int := 0;
  v_tasks         int := 0;
  v_planned       int := 0;
  v_topics        int := 0;
  v_published     int := 0;
  v_questions     int := 0;
  v_ai_questions  int := 0;
  v_templates     int := 0;
  v_tpl_shared    int := 0;
  v_results       int := 0;
  v_remarked      int := 0;
  v_subs          int := 0;
  v_leave_reviews int := 0;
  v_new_ids       uuid[] := ARRAY[]::uuid[];
BEGIN
  IF _user_id IS NULL THEN RETURN 0; END IF;

  -- These are badge_type = 'teacher'. Teachers and coordinators both teach and
  -- share one ladder; admins also create exams and mark attendance and should
  -- not collect it. user_roles is the authority, and holding either qualifying
  -- role alongside another one qualifies.
  IF NOT EXISTS (
    SELECT 1 FROM user_roles ur
    WHERE ur.user_id = _user_id AND ur.role IN ('teacher', 'coordinator')
  ) THEN
    RETURN 0;
  END IF;

  -- DISTINCT DATES, not rows. Marking one class of 40 students is one day of
  -- work, not 40; counting rows would hand out Never Misses on the first save.
  SELECT count(DISTINCT ar.date)::int INTO v_attendance
  FROM attendance_records ar
  WHERE ar.marked_by = _user_id;

  -- 'Lessons taught' means chapter delivery. A logged surprise test is real work
  -- but it is not a lesson (20260902120000).
  SELECT count(*)::int INTO v_lessons
  FROM tt_lesson_plans lp
  WHERE lp.owner_teacher_id = _user_id AND lp.status = 'done'
    AND lp.session_type = 'teaching';

  -- No status filter: the metric is exams CREATED. A paper that was written and
  -- then never published is still a paper the teacher wrote, and the AFTER
  -- INSERT trigger fires at exactly the moment this count moves.
  SELECT count(*)::int INTO v_exams
  FROM exams e
  WHERE e.created_by = _user_id;

  -- evaluated_by, NOT teacher_id. teacher_overrides has no teacher_id column;
  -- querying one is what made this metric read 0 for every teacher for months.
  --
  -- accepted_ai_suggestion = false is the "a human made the marking decision"
  -- test, and it is NOT the same as is_auto_graded = false. Measured over all
  -- 7,755 override rows in prod on 2026-08-18:
  --   auto=t acc=t  6,980  auto-grade-submission wrote the mark        -> machine
  --   auto=f acc=f    647  teacher marked from scratch                 -> human
  --   auto=f acc=t    110  teacher bulk-pressed "accept AI suggestion" -> machine
  --   auto=t acc=f     18  AI marked it, teacher then overrode it      -> human
  -- Filtering on is_auto_graded would keep the 110 button-presses and discard
  -- the 18 genuine corrections. 90% of this table is the model's work: counting
  -- it would have handed platinum "Marking Machine" to teachers who hand-marked
  -- nothing. Badges are irreversible here, so this errs toward under-counting.
  SELECT count(*)::int INTO v_answers
  FROM teacher_overrides t
  WHERE t.evaluated_by = _user_id
    AND NOT COALESCE(t.accepted_ai_suggestion, false);

  -- homework_assignments, not "homework": there is no table by that name.
  SELECT count(*)::int INTO v_hw_created
  FROM homework_assignments h
  WHERE h.created_by = _user_id;

  SELECT count(*)::int INTO v_hw_marked
  FROM homework_assignments h
  WHERE h.evaluated_by = _user_id;

  -- 'completed' is the only done state in prod. done_pending_approval is still
  -- waiting on someone else, so it is not the teacher's task finished yet.
  -- Multi-assignee work is FAN-OUT (N tasks rows sharing task_group_id, one
  -- assignment row each), so counting assignment rows counts people correctly.
  SELECT count(*)::int INTO v_tasks
  FROM task_assignments ta
  JOIN tasks tk ON tk.id = ta.task_id
  WHERE ta.assignee_id = _user_id AND tk.status = 'completed';

  -- Planned ahead. planned_at is stamped once, when the row first becomes
  -- 'planned' (tt_lesson_plans_stamp_status), and never moved afterwards, so a
  -- row that was planned on Monday for Wednesday still counts after it is
  -- taught, and a past lesson logged straight to 'done' (planned_at = now(),
  -- on or after the period date) never does. Chapter required: a row with no
  -- topic is a placeholder, not a plan. Note-only rows are activity logs.
  -- §24: institution timezone, never UTC.
  SELECT count(*)::int INTO v_planned
  FROM tt_lesson_plans lp
  JOIN institutions i ON i.id = lp.institution_id
  WHERE lp.owner_teacher_id = _user_id
    AND lp.planned_at IS NOT NULL
    AND (lp.planned_at AT TIME ZONE i.timezone)::date < lp.date
    AND lp.session_type = 'teaching'
    AND NOT lp.is_note_only
    AND lp.topic_id IS NOT NULL;

  -- DISTINCT chapters, not rows: the same chapter completed for two sections is
  -- one chapter taught twice. Every source counts, including the 'correction'
  -- rows the 20260704140000 backfill wrote from historical done lessons; they
  -- are the teacher's real teaching history, not corrections in the UI sense.
  SELECT count(DISTINCT e.topic_id)::int INTO v_topics
  FROM syllabus_progress_events e
  WHERE e.recorded_by = _user_id AND e.action = 'completed';

  -- Published papers. 'active' is a published exam inside its window, and
  -- 'completed' is one whose window has closed; all three reached students.
  -- 'archived' is excluded: an archived draft and an archived completed exam
  -- are indistinguishable, and this errs toward under-counting.
  SELECT count(*)::int INTO v_published
  FROM exams e
  WHERE e.created_by = _user_id
    AND e.status IN ('published', 'active', 'completed');

  -- question_bank.source is free text with no CHECK; the app writes 'manual'
  -- (typed questions), 'ai_generated' (AI batches the teacher kept) and
  -- 'bulk_upload' (admin spreadsheet import, not counted).
  SELECT count(*)::int INTO v_questions
  FROM question_bank q
  WHERE q.created_by = _user_id AND q.source = 'manual';

  SELECT count(*)::int INTO v_ai_questions
  FROM question_bank q
  WHERE q.created_by = _user_id AND q.source = 'ai_generated';

  SELECT count(*)::int                        INTO v_templates
  FROM exam_templates t WHERE t.created_by = _user_id;

  SELECT count(*)::int                        INTO v_tpl_shared
  FROM exam_templates t WHERE t.created_by = _user_id AND t.is_shared;

  -- DISTINCT exams, joined through the attempt: final_results carries only
  -- attempt_id. finalized_by is the validator, published_by the publisher; the
  -- same two columns drive the onboarding milestone first_result_validated, so
  -- this badge and that milestone can never disagree about "has this teacher
  -- ever finished a result".
  SELECT count(DISTINCT sea.exam_id)::int INTO v_results
  FROM final_results fr
  JOIN student_exam_attempts sea ON sea.id = fr.attempt_id
  WHERE fr.finalized_by = _user_id OR fr.published_by = _user_id;

  -- DISTINCT students, not remarks. Ten remarks on one child is attention to
  -- one child; the ladder rewards breadth.
  SELECT count(DISTINCT r.student_id)::int INTO v_remarked
  FROM student_remarks r
  WHERE r.teacher_id = _user_id;

  -- Only rows that name this teacher as the substitute count, and only once
  -- the cover is real: 'pending' and 'no_teacher_available' rows have no
  -- substitute (tt_substitutions_assigned_has_sub_chk), 'cancelled' never
  -- happened. Being the original (absent) teacher earns nothing.
  SELECT count(*)::int INTO v_subs
  FROM tt_substitutions s
  WHERE s.substitute_teacher_id = _user_id
    AND s.status IN ('assigned', 'completed');

  -- Student-filed requests the teacher decided. source = 'staff' rows are
  -- leaves a teacher marked on the student's behalf through
  -- review_student_leave / the attendance flow, already approved on insert:
  -- that is attendance-taking, not reviewing, and is excluded.
  SELECT count(*)::int INTO v_leave_reviews
  FROM leave_requests lr
  WHERE lr.reviewed_by = _user_id
    AND lr.status IN ('approved', 'rejected')
    AND lr.source = 'student';

  IF GREATEST(v_attendance, v_lessons, v_exams, v_answers,
              v_hw_created, v_hw_marked, v_tasks, v_planned, v_topics,
              v_published, v_questions, v_ai_questions, v_templates, v_tpl_shared,
              v_results, v_remarked, v_subs, v_leave_reviews) = 0 THEN
    RETURN 0;
  END IF;

  SELECT p.institution_id INTO v_inst FROM profiles p WHERE p.id = _user_id;

  -- Awards and progress in ONE statement off one metrics tuple, so the two can
  -- never disagree about what the teacher's numbers are. Both CTEs are
  -- data-modifying and therefore both execute, whether or not the outer query
  -- references them.
  WITH m (metric, val) AS (
    VALUES ('attendance_days_marked'::text,  v_attendance),
           ('lessons_taught',                v_lessons),
           ('exams_created',                 v_exams),
           ('answers_evaluated',             v_answers),
           ('homework_created',              v_hw_created),
           ('homework_marked',               v_hw_marked),
           ('tasks_completed',               v_tasks),
           ('lessons_planned_ahead',         v_planned),
           ('syllabus_topics_completed',     v_topics),
           ('exams_published',               v_published),
           ('questions_authored',            v_questions),
           ('ai_questions_saved',            v_ai_questions),
           ('templates_created',             v_templates),
           ('templates_shared',              v_tpl_shared),
           ('results_published',             v_results),
           ('students_remarked',             v_remarked),
           ('substitutions_covered',         v_subs),
           ('leave_reviews_done',            v_leave_reviews)
  ),
  tb AS (
    SELECT bd.id, bd.criteria_metric, bd.criteria_value, m.val
    FROM badge_definitions bd
    JOIN m ON m.metric = bd.criteria_metric
    WHERE bd.is_active AND bd.badge_type = 'teacher'
  ),
  ins AS (
    INSERT INTO user_badges
      (user_id, badge_id, institution_id, source_entity_type, metadata)
    SELECT _user_id, tb.id, v_inst, tb.criteria_metric,
           jsonb_build_object('count', tb.val)
    FROM tb
    WHERE tb.val >= tb.criteria_value
    -- Deterministic lock order: two evaluator runs for the SAME teacher (an
    -- exam publish in one tab, a remark saved in another) upsert the same rows;
    -- without ORDER BY the join may emit them in different orders and the two
    -- sessions can deadlock, which the trigger wrapper would then swallow as a
    -- WARNING and the badge would silently not be awarded.
    ORDER BY tb.id
    -- Bare DO NOTHING: the guard is the expression index
    -- user_badges_once_per_period_idx (user_id, badge_id, COALESCE(period_key,'')),
    -- which cannot be named as a conflict target by column list.
    ON CONFLICT DO NOTHING
    RETURNING id
  ),
  prog AS (
    INSERT INTO badge_progress
      (user_id, badge_id, institution_id, current_value, target_value, last_updated)
    -- Every rung, earned or not, so an unearned tile reads "10 of 25" instead of
    -- a bar frozen at zero.
    SELECT _user_id, tb.id, v_inst, tb.val, tb.criteria_value, now()
    FROM tb
    ORDER BY tb.id   -- same lock-order reason as the awards insert above
    ON CONFLICT (user_id, badge_id) DO UPDATE
      SET current_value  = EXCLUDED.current_value,
          target_value   = EXCLUDED.target_value,
          institution_id = EXCLUDED.institution_id,
          last_updated   = now()
    RETURNING 1
  )
  SELECT COALESCE(array_agg(id), ARRAY[]::uuid[]) INTO v_new_ids FROM ins;

  -- Notifications in their OWN subtransaction, AFTER the award has landed. When
  -- these shared a statement with the award, a notifications failure rolled the
  -- award back with it, so the notification path could revoke a badge.
  IF _notify AND array_length(v_new_ids, 1) IS NOT NULL THEN
    BEGIN
      INSERT INTO notifications (user_id, type, title, message, link, metadata)
      SELECT ub.user_id, 'badge_earned',
             'Badge earned: ' || bd.name,
             'You earned the "' || bd.name || '" badge (+' || bd.points || ' points).',
             '/achievements',
             jsonb_build_object('badge_id', bd.id, 'badge_name', bd.name, 'points', bd.points)
      FROM user_badges ub
      JOIN badge_definitions bd ON bd.id = ub.badge_id
      WHERE ub.id = ANY (v_new_ids);
    EXCEPTION WHEN OTHERS THEN
      RAISE WARNING 'evaluate_teacher_badges: awards committed, notifications failed: %', SQLERRM;
    END;
  END IF;

  RETURN COALESCE(array_length(v_new_ids, 1), 0);
END $$;

-- ── 4. Triggers ─────────────────────────────────────────────────────────────
-- trg_zz_* naming, and every body wrapped in BEGIN / EXCEPTION WHEN OTHERS /
-- RAISE WARNING: a badge fault must never roll back the teacher's own write
-- (20260818120000 §6). Hot tables get statement-level triggers with a
-- transition table so a bulk write is one evaluator run per actor.

-- 4a. exams, publish side. The existing INSERT trigger already evaluates on
--     creation (and an exam inserted straight into 'published' is counted by
--     it). This catches the draft -> published transition, which is an UPDATE
--     of status. Reuses tg_zz_teacher_badges_exam(), which reads
--     NEW.created_by. OLD guard so an active -> completed sweep by the cron
--     does not run eighteen aggregates per exam for a count that has not moved.
DROP TRIGGER IF EXISTS trg_zz_teacher_badges_exam_published ON public.exams;
CREATE TRIGGER trg_zz_teacher_badges_exam_published
AFTER UPDATE OF status ON public.exams
FOR EACH ROW WHEN (NEW.created_by IS NOT NULL
                   AND NEW.status IN ('published', 'active', 'completed')
                   AND OLD.status NOT IN ('published', 'active', 'completed'))
EXECUTE FUNCTION public.tg_zz_teacher_badges_exam();

-- 4b. question_bank. Statement-level: an AI batch or a manual case study
--     inserts many rows in one statement, and the busiest author has thousands
--     of rows. Filtered to the two sources that count so a bulk_upload import
--     never enters the loop.
CREATE OR REPLACE FUNCTION public.tg_zz_teacher_badges_question_bank()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE r record;
BEGIN
  BEGIN
    FOR r IN
      SELECT DISTINCT n.created_by AS teacher_id
      FROM newrows n
      WHERE n.created_by IS NOT NULL
        AND n.source IN ('manual', 'ai_generated')
    LOOP
      PERFORM public.evaluate_teacher_badges(r.teacher_id);
    END LOOP;
  EXCEPTION WHEN OTHERS THEN
    RAISE WARNING 'tg_zz_teacher_badges_question_bank failed: %', SQLERRM;
  END;
  RETURN NULL;
END $$;

DROP TRIGGER IF EXISTS trg_zz_teacher_badges_question_bank ON public.question_bank;
CREATE TRIGGER trg_zz_teacher_badges_question_bank
AFTER INSERT ON public.question_bank
REFERENCING NEW TABLE AS newrows
FOR EACH STATEMENT
EXECUTE FUNCTION public.tg_zz_teacher_badges_question_bank();

-- 4c. A generic row-level function for any table whose actor column is
--     created_by. tg_zz_teacher_badges_exam() has the same body but its
--     warning names exams; this one is table-agnostic and is what future
--     created_by-shaped ladders should attach to.
CREATE OR REPLACE FUNCTION public.tg_zz_teacher_badges_creator()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  BEGIN
    PERFORM public.evaluate_teacher_badges(NEW.created_by);
  EXCEPTION WHEN OTHERS THEN
    RAISE WARNING 'tg_zz_teacher_badges_creator (%) failed for %: %', TG_TABLE_NAME, NEW.created_by, SQLERRM;
  END;
  RETURN NULL;
END $$;

-- exam_templates: one row per save, created_by NOT NULL. Shared flips via an
-- UPDATE of is_shared; guard on the false -> true edge only.
DROP TRIGGER IF EXISTS trg_zz_teacher_badges_template ON public.exam_templates;
CREATE TRIGGER trg_zz_teacher_badges_template
AFTER INSERT ON public.exam_templates
FOR EACH ROW WHEN (NEW.created_by IS NOT NULL)
